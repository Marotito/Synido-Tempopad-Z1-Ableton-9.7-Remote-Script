def velocity_de_clip(color_entero):
    """Velocity que corresponde al color de un clip de Live.

    Primero busca en la tabla OFICIAL de Ableton (coincidencia exacta
    con los 60 colores de la paleta de clips). Si el color no esta en
    la tabla -por ejemplo un clip con color personalizado- cae al mas
    parecido por distancia RGB.
    """
    if color_entero in CLIP:
        return CLIP[color_entero]
    r = (color_entero >> 16) & 255
    g = (color_entero >> 8) & 255
    b = color_entero & 255
    if r == 0 and g == 0 and b == 0:
        return APAGADO
    return mas_cercano(r, g, b)


def mas_cercano(r, g, b):
    """Velocity mas parecida a un RGB arbitrario, por distancia
    euclidea sobre los 128 colores reales del aparato."""
    mejor, mejor_d = BLANCO, None
    for v in range(1, 128):
        cr, cg, cb = RGB[v]
        d = (cr - r) ** 2 + (cg - g) ** 2 + (cb - b) ** 2
        if mejor_d is None or d < mejor_d:
            mejor, mejor_d = v, d
    return mejor
